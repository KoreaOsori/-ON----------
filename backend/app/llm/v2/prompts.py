def build_clarification_answer(candidates: list[dict], limit: int = 8, food_combination: bool = False) -> str:
    """제품 후보가 여럿이고 근거를 못 찾았을 때 사용자에게 보여 줄 되묻기. 모델 문장이 아니라 코드가 만든다."""
    lines = ["어느 제품을 말씀하시는지 확인이 필요해요. 아래 중 정확한 제품명(괄호 안 내용 포함)을 알려 주세요."]
    for index, item in enumerate(candidates[:limit], start=1):
        maker = f" ({item['manufacturer']})" if item.get("manufacturer") else ""
        lines.append(f"{index}. {item['product_name']}{maker}")
    if len(candidates) > limit:
        lines.append(f"…외 {len(candidates) - limit}개")
    if food_combination:
        lines.extend(["", FOOD_COMBINATION_NOTE])
    return "\n".join(lines)


def build_user_content(
    question: str, profile_context: str | None, product_key: str | None = None, products: list[str] | None = None
) -> str:
    """첫 user 메시지. 약 정보는 넣지 않는다(도구로 찾는다)."""
    parts = []
    if profile_context:
        parts.append(f"[사용자 정보]\n{profile_context}")
    if products:
        parts.append("[확인된 제품명]\n" + "\n".join(f"- {name}" for name in products))
    if product_key:
        parts.append(f"[선택한 제품 ID]\n{product_key}")
    parts.append(f"[질문]\n{question}")
    return "\n\n".join(parts)
