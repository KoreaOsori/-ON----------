"""질문 단계의 안전 점검 (모델 호출 전에 코드로 판단).

기존 chat/service.py 의 EMERGENCY_PATTERN 은 '심각' 처럼 범위가 넓어서, v2 는 의미가 분명한 표현 위주로 따로 둔다.
어디까지나 보조 장치다. 놓치는 표현이 있을 수 있어 시스템 프롬프트의 규칙 6 도 함께 쓴다.
"""
import re

EMERGENCY_PATTERN = re.compile(
    r"응급|호흡\s*곤란|숨\s*(이|을)?\s*(안|못)\s*(쉬|쉴|쉬어)|숨쉬기\s*(힘|어렵)|숨이\s*차|의식\s*(이)?\s*(없|잃|저하|흐려|혼미)|"
    r"쇼크|아나필락|경련|발작|가슴\s*(이)?\s*(아파|조여|답답)|(입술|얼굴|목|혀).{0,6}(붓|부어|부은)|"
    r"피를?\s*토|토혈|혈변|심한\s*알레르기"
)

# 이미 약을 너무 많이(또는 잘못) 먹었다는 표현. 고의가 드러나지 않은 과다복용·오복용이며, 증상이 없어도 응급 연락을 먼저 안내한다.
# "한 통에 몇 알이에요?" 같은 질문은 잡지 않도록 '먹었다/삼켰다'처럼 이미 먹은 표현이 뒤따를 때만 본다.
_ATE = r"(먹었|먹어\s*버렸|먹어버렸|삼켰|마셨|복용했)"
OVERDOSE_PATTERN = re.compile(
    r"과다\s*복용|과량\s*복용|과량으로|"
    rf"(한|두|세|여러|반)\s*(통|병|봉지|상자|갑|팩|박스)\s*(을|를)?\s*(다|전부|거의|넘게)?\s*{_ATE}|"
    rf"(?<!\d)([5-9]|\d{{2,}})\s*(알|정|개|캡슐|포)\s*(을|를|이나|씩)?\s*(한꺼번에|한번에|한\s*번에|넘게)?\s*{_ATE}|"
    rf"(열|스무|수십)\s*(알|정|개)\s*(을|를|이나|넘게)?\s*{_ATE}|"
    rf"(너무|잔뜩|엄청|훨씬)\s*많이\s*{_ATE}|"
    rf"(실수로|잘못)\s*.{{0,12}}{_ATE}"
)

# 자해·고의 과다복용을 시사하는 표현. 약을 모으는 행동("수면제를 모아두고")과 삶을 끝내고 싶다는 표현도 포함한다.
_HOARD_DRUGS = r"(약|알약|수면제|수면\s*유도제|수면\s*유도\s*제|진통제|안정제|신경\s*안정제|항우울제)"
CRISIS_PATTERN = re.compile(
    r"자살|자해|죽고\s*싶|목숨을?\s*끊|극단적\s*선택|(약|알약).{0,10}(전부|다|한꺼번에|몽땅).{0,6}(먹|삼키|털어)|"
    r"(전부|한꺼번에|몽땅).{0,10}(먹|삼키|털어).{0,10}(죽|죽을)|"
    rf"{_HOARD_DRUGS}\s*(을|를)?\s*.{{0,6}}(모아\s*(두|놓|뒀|놨|둔)|모으고|모았|사\s*모으|사\s*모아)|"
    r"살기\s*(가\s*)?싫|사라지고\s*싶|없어지고\s*싶|죽어\s*버리고\s*싶|삶을?\s*끝내|생을?\s*마감|"
    r"(깨어나지|눈\s*뜨지)\s*않았으면"
)

# 복용을 끊어도 되는지, 줄여도 되는지 묻는 질문. 이런 판단은 근거 검색 없이 전문가 상담 안내로 답한다.
# "언제 복용을 중단해야 하나요" 같은 주의사항 질문은 잡지 않도록 허락·판단을 묻는 어미가 뒤따를 때만 본다.
STOP_PATTERN = re.compile(
    r"(끊|중단|멈추|멈춰|그만\s*(먹|복용|드)|먹지\s*않|안\s*먹|안\s*드시|안\s*드셔)[^?？.!]{0,12}?(돼|되|될|괜찮|상관|좋을까|할까|말까)"
)


def is_overdose(question: str) -> bool:
    return bool(OVERDOSE_PATTERN.search(question))


def is_emergency(question: str) -> bool:
    return bool(EMERGENCY_PATTERN.search(question)) or is_overdose(question)


def is_crisis(question: str) -> bool:
    return bool(CRISIS_PATTERN.search(question))


def is_stop_question(question: str) -> bool:
    return bool(STOP_PATTERN.search(question))
